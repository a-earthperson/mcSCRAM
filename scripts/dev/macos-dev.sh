#!/usr/bin/env bash
# Local macOS toolchain for fuzzybits: Homebrew LLVM 20 + AdaptiveCpp
# (Metal + OpenMP on arm64, OpenMP only on x86_64) + Boost + metal-cpp,
# built by the same scripts/ci/macos-* scripts as macos.yml into <repo>/.cache.
#
# Usage: scripts/dev/macos-dev.sh [bootstrap|doctor]
#   bootstrap  install or rebuild whatever is missing or no longer matches
#              toolchain.env, then write .cache/macos-dev.env (default)
#   doctor     report toolchain state; change nothing; exit 1 on hard failures
#
# Afterwards:
#   source .cache/macos-dev.env
#   cmake --workflow --preset metal-local
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${root}"

die() { echo "error: $*" >&2; exit 1; }

[[ "$(uname -s)" == "Darwin" ]] || die "macOS only"
arch="$(uname -m)"
if [[ "${arch}" == "arm64" ]]; then
  metal=ON
  deployment_target=26.0
else
  metal=OFF
  deployment_target=15.0
fi
# Same targets as the macos-wheel jobs, so prebuilt Boost/AdaptiveCpp objects
# link into wheels without "built for newer macOS" mismatches.
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-${deployment_target}}"

set -a
# shellcheck disable=SC1091
. ./toolchain.env
set +a

cache="${root}/.cache"
env_file="${cache}/macos-dev.env"
export ACPP_PREFIX="${cache}/acpp-prefix"
export BOOST_PREFIX="${cache}/boost-prefix"
export METAL_CPP_DIR="${cache}/metal-cpp"
export RUNNER_TEMP="${cache}/tmp"
export WITH_METAL_BACKEND="${metal}"
export HOMEBREW_NO_AUTO_UPDATE="${HOMEBREW_NO_AUTO_UPDATE:-1}"
export HOMEBREW_NO_INSTALLED_DEPENDENTS_CHECK="${HOMEBREW_NO_INSTALLED_DEPENDENTS_CHECK:-1}"

formulae=(llvm@20 lld@20 libomp ninja ccache coreutils cmake)

# SDK 27's math.h includes <float.h> under __need_infinity_nan when
# __has_feature(modules), which Homebrew clang 20 reports in C++20+ modes.
# LLVM 20's libc++ <float.h> include guard then hides FLT_* from every later
# <cfloat>, and Boost.Math's <boost/cstdfloat.hpp> #errors. SDK 26 (what the
# hosted macos-26 runners use) predates that math.h change.
# Override with FUZZYBITS_MACOS_SDK=/path/to/MacOSX<ver>.sdk.
select_sdk() {
  if [[ -n "${FUZZYBITS_MACOS_SDK:-}" ]]; then
    echo "${FUZZYBITS_MACOS_SDK}"
    return
  fi
  local dev d c
  dev="$(xcode-select -p 2>/dev/null)" || return 1
  for d in "${dev}/SDKs" "${dev}/Platforms/MacOSX.platform/Developer/SDKs"; do
    for c in "${d}/MacOSX26.sdk" "${d}"/MacOSX26.*.sdk; do
      if [[ -d "${c}" ]]; then
        echo "${c}"
        return
      fi
    done
  done
  xcrun --show-sdk-path 2>/dev/null
}

sdk_version() { SDKROOT="$1" xcrun --show-sdk-version 2>/dev/null; }

shell_sdkroot="${SDKROOT:-}"
if SDKROOT="$(select_sdk)" && [[ -n "${SDKROOT}" ]]; then
  export SDKROOT
else
  unset SDKROOT
fi

# Sets LLVM_PREFIX / OMP_PREFIX / ACPP_LLD_PATH; returns 1 if a keg is missing.
# lld@20 specifically: bundle_acpp.py ships its liblld*.dylib next to LLVM 20.
resolve_brew_prefixes() {
  LLVM_PREFIX="$(brew --prefix --installed llvm@20 2>/dev/null)" || return 1
  OMP_PREFIX="$(brew --prefix --installed libomp 2>/dev/null)" || return 1
  local lld_prefix
  lld_prefix="$(brew --prefix --installed lld@20 2>/dev/null)" || return 1
  ACPP_LLD_PATH="${lld_prefix}/bin/ld64.lld"
  [[ -x "${ACPP_LLD_PATH}" ]] || return 1
  export LLVM_PREFIX OMP_PREFIX ACPP_LLD_PATH
}

write_env_file() {
  cat > "${env_file}" <<EOF
# Generated by scripts/dev/macos-dev.sh. Source from zsh or bash.
export ACPP_PREFIX="${ACPP_PREFIX}"
export BOOST_PREFIX="${BOOST_PREFIX}"
export METAL_CPP_DIR="${METAL_CPP_DIR}"
export LLVM_PREFIX="${LLVM_PREFIX}"
export OMP_PREFIX="${OMP_PREFIX}"
export ACPP_LLD_PATH="${ACPP_LLD_PATH}"
export AdaptiveCpp_DIR="${ACPP_PREFIX}/lib/cmake/AdaptiveCpp"
# xcrun and CMake (CMAKE_OSX_SYSROOT default) read SDKROOT; Homebrew clang
# ignores it, so builds must pass -isysroot, which CMake does from the cache.
export SDKROOT="${SDKROOT}"
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET}"
# LLVM 20 goes last so /usr/bin/clang stays the host compiler.
case ":\${PATH}:" in
  *":${ACPP_PREFIX}/bin:"*) ;;
  *) export PATH="${ACPP_PREFIX}/bin:\${PATH}:${LLVM_PREFIX}/bin" ;;
esac
# SIP drops DYLD_* when exec'ing protected binaries (/bin/sh, /usr/bin/env),
# so scripts with an env shebang must re-export it themselves.
case ":\${DYLD_LIBRARY_PATH:-}:" in
  *":${ACPP_PREFIX}/lib:"*) ;;
  *) export DYLD_LIBRARY_PATH="${ACPP_PREFIX}/lib:${OMP_PREFIX}/lib\${DYLD_LIBRARY_PATH:+:\${DYLD_LIBRARY_PATH}}" ;;
esac
EOF
  echo "wrote ${env_file}"
}

failures=0
ok()   { printf '  ok    %s\n' "$*"; }
warn() { printf '  warn  %s\n' "$*"; }
fail() { printf '  FAIL  %s\n' "$*"; failures=$((failures + 1)); }

doctor() {
  failures=0
  echo "== host"
  local os_ver os_major
  os_ver="$(sw_vers -productVersion)"
  os_major="${os_ver%%.*}"
  if [[ "${arch}" == "arm64" ]] && (( os_major < 26 )); then
    warn "macOS ${os_ver} ${arch}: Metal kernels need macOS 26+ (MSL 4.0); OpenMP only"
  elif [[ "${arch}" == "arm64" ]] && (( os_major != 26 )); then
    warn "macOS ${os_ver} ${arch}: hosted CI covers macOS 26 only"
  else
    ok "macOS ${os_ver} ${arch} (Metal backend ${metal})"
  fi
  local sdk_ver
  if [[ -n "${SDKROOT:-}" ]] && sdk_ver="$(sdk_version "${SDKROOT}")"; then
    if (( ${sdk_ver%%.*} >= 27 )); then
      fail "SDK ${sdk_ver} at ${SDKROOT}: LLVM 20 cannot build Boost.Math <cstdfloat>" \
        "against SDK 27+; install a macOS 26 SDK or set FUZZYBITS_MACOS_SDK"
    else
      ok "SDK ${sdk_ver} at ${SDKROOT}"
    fi
    if [[ -n "${shell_sdkroot}" && "${shell_sdkroot}" != "${SDKROOT}" ]]; then
      warn "shell SDKROOT=${shell_sdkroot} differs; re-source .cache/macos-dev.env"
    fi
  else
    fail "no macOS SDK; run: xcode-select --install"
  fi

  echo "== Homebrew"
  if ! command -v brew >/dev/null 2>&1; then
    fail "brew not found (https://brew.sh)"
  else
    local f v
    for f in "${formulae[@]}"; do
      if v="$(brew list --versions "${f}" 2>/dev/null)" && [[ -n "${v}" ]]; then
        ok "${v}"
      else
        fail "${f} not installed"
      fi
    done
  fi
  if command -v uv >/dev/null 2>&1; then
    ok "$(uv --version) (wheel builds)"
  else
    warn "uv not found; needed by scripts/ci/macos-wheel-versions.sh"
  fi

  echo "== prefixes (${cache})"
  local have_brew=0
  if command -v brew >/dev/null 2>&1 && resolve_brew_prefixes; then
    have_brew=1
  fi
  if [[ "${metal}" == "ON" ]]; then
    if [[ -f "${METAL_CPP_DIR}/Metal/Metal.hpp" ]] \
        && [[ "$(cat "${METAL_CPP_DIR}/.fuzzybits-pin" 2>/dev/null)" == "${METAL_CPP_VERSION}" ]]; then
      ok "metal-cpp ${METAL_CPP_VERSION}"
    else
      fail "metal-cpp missing or not ${METAL_CPP_VERSION}"
    fi
  fi
  if bash scripts/ci/macos-boost-build.sh --check; then
    ok "Boost ${BOOST_VERSION}"
  else
    warn "Boost ${BOOST_VERSION} prefix missing or stale (configure falls back to FetchContent)"
  fi
  if (( have_brew )) && bash scripts/ci/macos-acpp-build.sh --check >/dev/null 2>&1; then
    ok "AdaptiveCpp ${ACPP_REF_METAL:0:12} (LLVM $("${LLVM_PREFIX}/bin/llvm-config" --version))"
    local devices
    devices="$(DYLD_LIBRARY_PATH="${ACPP_PREFIX}/lib:${OMP_PREFIX}/lib" \
      "${ACPP_PREFIX}/bin/acpp-info" -l 2>&1 || true)"
    if [[ "${metal}" == "ON" ]]; then
      if grep -qiE 'metal' <<<"${devices}"; then
        ok "Metal device visible to acpp-info"
      else
        warn "no Metal device in acpp-info -l"
      fi
    fi
    if grep -qiE 'omp|openmp' <<<"${devices}"; then
      ok "OpenMP host device visible to acpp-info"
    else
      fail "no OpenMP device in acpp-info -l"
    fi
  else
    fail "AdaptiveCpp prefix missing or not built from current pins"
  fi
  if [[ -f "${env_file}" ]]; then
    ok "${env_file#"${root}/"}"
  else
    fail "${env_file#"${root}/"} missing"
  fi

  echo "== repo"
  local uninit
  uninit="$(git submodule status 2>/dev/null | grep -c '^-' || true)"
  if (( uninit > 0 )); then
    warn "${uninit} submodule(s) not initialised; run: git submodule update --init --recursive"
  else
    ok "submodules initialised"
  fi

  if (( failures > 0 )); then
    echo "${failures} failure(s); run: scripts/dev/macos-dev.sh bootstrap"
    return 1
  fi
  echo "toolchain ready; next: source ${env_file#"${root}/"} && cmake --workflow --preset metal-local"
}

bootstrap() {
  [[ -n "${SDKROOT:-}" ]] || die "no macOS SDK; run: xcode-select --install"
  echo "SDKROOT=${SDKROOT} ($(sdk_version "${SDKROOT}")), MACOSX_DEPLOYMENT_TARGET=${MACOSX_DEPLOYMENT_TARGET}"
  command -v brew >/dev/null 2>&1 || die "Homebrew required (https://brew.sh)"
  test "${ACPP_REF_METAL}" != "TBD"
  test "${METAL_CPP_VERSION}" != "TBD"

  echo "== Homebrew"
  bash scripts/ci/macos-brew-deps.sh
  command -v uv >/dev/null 2>&1 || brew install uv
  resolve_brew_prefixes \
    || die "llvm@20, lld@20 (with bin/ld64.lld) and libomp must be installed kegs"

  echo "== submodules"
  git submodule update --init --recursive

  mkdir -p "${RUNNER_TEMP}"
  if [[ "${metal}" == "ON" ]]; then
    echo "== metal-cpp"
    bash scripts/ci/macos-metal-cpp-fetch.sh
  fi
  echo "== Boost"
  bash scripts/ci/macos-boost-build.sh
  echo "== AdaptiveCpp"
  bash scripts/ci/macos-acpp-build.sh

  write_env_file
  echo
  doctor
}

case "${1:-bootstrap}" in
  bootstrap) bootstrap ;;
  doctor) doctor ;;
  -h|--help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0" ;;
  *) die "usage: $0 [bootstrap|doctor]" ;;
esac
